// Splits on paragraph breaks so a section is never cut mid-sentence, keeping
// each message safely under Telegram's ~4096-character limit.
function chunkText(text, maxLen = 3500) {
  const paragraphs = text.split("\n\n");
  const chunks = [];
  let current = "";
  for (const para of paragraphs) {
    const candidate = current ? `${current}\n\n${para}` : para;
    if (candidate.length > maxLen && current) {
      chunks.push(current);
      current = para;
    } else {
      current = candidate;
    }
  }
  if (current) chunks.push(current);
  return chunks;
}

// The document itself is only maintained in Uzbek (translating a legal text
// accurately into ru/en is out of scope here) -- non-Uzbek users get a short
// trilingual heads-up before the Uzbek text.
async function sendPolicyDocument(ctx, lang) {
  const chunks = chunkText(POLICY_TEXT);
  if (lang !== "uz") {
    await ctx.reply(
      "ℹ️ Ushbu hujjat hozircha faqat o'zbek tilida mavjud.\n" +
        "This document is currently only available in Uzbek.\n" +
        "Этот документ пока доступен только на узбекском языке."
    );
  }
  for (const chunk of chunks) {
    await ctx.reply(chunk);
  }
}

